//! RTL8125B ("MAC_R25B") bring-up tables, transcribed from OpenBSD's rge(4)
//! driver (`sys/dev/pci/if_rge.c` + `if_rgereg.h`, fetched 2026-06-08) — the
//! known-working 8125B driver that ships these register tables IN-SOURCE rather
//! than loading firmware files, which is what makes them transcribable here.
//!
//! Provenance and licensing: OpenBSD's rge(4) is Copyright (c) 2019-2024
//! Kevin Lo <kevlo@openbsd.org>, distributed under OpenBSD's ISC-style permissive
//! license, which is compatible with this repository's MIT license. What is
//! reproduced here is the register/value tables (facts about the hardware) plus
//! their replay order; the surrounding driver logic is this crate's own.
//!
//! Three tables, applied in bring-up order:
//!
//! * [`MAC_MCU`] — the MAC-side MCU patch (`rtl8125b_mac_bps`): replayed into MAC
//!   OCP after the MCU is halted (`rge_mac_config_mcu`, MAC_R25B arm; ram page 0).
//! * [`EPHY`] — the PCIe SerDes (EPHY) tuning (`mac_r25b_ephy`), written through
//!   `EPHYAR` (0x80) with rge's 7-bit address mask (`rge_ephy_config_mac_r25b`).
//! * [`PHY_MCU`] — the GPHY MCU patch (`MAC_R25B_MCU`), 1447 PHY-OCP writes
//!   replayed inside the 0xb820/0xb800 patch-mode bracket, only when the PHY's ram
//!   code version (OCP 0xa436=0x801e -> 0xa438) differs from
//!   [`PHY_MCU_VERSION`] (`rge_phy_config_mcu`, MAC_R25B arm).

